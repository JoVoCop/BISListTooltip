#!/usr/bin/env python3
"""Regenerates Data/BuiltinLists.lua and Data/Tokens.lua from the website's built-in lists."""
import argparse
import base64
import binascii
import json
import os
import re
import sys
import urllib.error
import urllib.request
import zlib
from pathlib import Path
from typing import Any

REPO_DIR = Path(__file__).resolve().parent.parent
DEFAULT_SITE = "https://bislist.io"
# The site refuses Python's default user agent, so the sync names itself.
USER_AGENT = "BISListTooltip-sync/1.0 (+https://github.com/JoVoCop/BISListTooltip)"
BUILTIN_LISTS_FILE = "BuiltinLists.lua"
TOKENS_FILE = "Tokens.lua"
GENERATED_HEADER = "-- Generated by tools/sync-builtin.py. Do not edit.\nlocal _, ns = ...\n"
INTEGER = re.compile(r"[0-9]+")
MAX_BUILD_CHARACTERS = 32
DAYS_IN_MONTH = (31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)


class SyncError(Exception):
    pass


def fetch_builtin(site: str) -> dict[str, Any]:
    url = site.rstrip("/") + "/api/addon/builtin"
    headers = {"User-Agent": USER_AGENT}
    # The endpoint only answers the sync, which proves itself with the key the site holds as ADDON_SYNC_KEY.
    key = os.environ.get("BISLIST_SYNC_KEY", "")
    if key:
        headers["X-Addon-Sync-Key"] = key
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=30) as response:
            data = json.load(response)
    except urllib.error.HTTPError as error:
        if error.code == 401:
            raise SyncError(f"{url} refused the request; set BISLIST_SYNC_KEY to the site's sync key") from error
        raise
    if not isinstance(data, dict):
        raise SyncError(f"{url} did not return a JSON object")
    return data


def decode_import_string(import_string: str) -> dict[str, Any]:
    text = re.sub(r"[ \t\r\n]", "", import_string)
    if not text.startswith("BLT1:"):
        raise SyncError("import string has the wrong prefix (expected BLT1:)")
    try:
        compressed = base64.b64decode(text[len("BLT1:"):], validate=True)
        body = zlib.decompress(compressed, -15).decode("utf-8")
    except (binascii.Error, zlib.error, UnicodeDecodeError) as error:
        raise SyncError(f"import string cannot be decoded: {error}") from error
    lines = body.split("\n")
    fields = lines[0].split("\t")
    if len(fields) != 7 or fields[0] != "H":
        raise SyncError("import string has no valid H line")
    if not (INTEGER.fullmatch(fields[2]) and INTEGER.fullmatch(fields[3])):
        raise SyncError("H line has a non-integer version or publishedAt")
    for number, line in enumerate(lines[1:], start=2):
        validate_entry_line(number, line)
    return {
        "listId": fields[1],
        "version": int(fields[2]),
        "publishedAt": int(fields[3]),
        "game": fields[4],
        "title": fields[5],
        "author": fields[6],
    }


# Unknown classes and slot groups are deliberately accepted: the addon skips them
# and the site may know more than this checkout of Catalog.lua.
def validate_entry_line(number: int, line: str) -> None:
    fields = line.split("\t")
    if len(fields) != 7 or fields[0] != "E":
        raise SyncError(f"line {number} is not an E line with 7 fields")
    if not 1 <= len(fields[2]) <= MAX_BUILD_CHARACTERS or "\r" in fields[2]:
        raise SyncError(f"line {number} has a build that is empty, too long or contains a line break")
    for name, value in (("itemId", fields[3]), ("rank", fields[5])):
        if not INTEGER.fullmatch(value) or int(value) < 1:
            raise SyncError(f"line {number} has an invalid {name}")


def parse_lua_string_list(source: str, variable: str) -> list[str]:
    match = re.search(variable + r"\s*=\s*\{(.*?)\}", source, re.DOTALL)
    if match is None:
        raise SyncError(f"{variable} not found in Catalog.lua")
    return re.findall(r'"([^"]*)"', match.group(1))


def check_catalog(catalog: dict[str, Any], catalog_path: str) -> None:
    source = Path(catalog_path).read_text(encoding="utf-8")
    expected = {
        "classes": parse_lua_string_list(source, "CLASS_TOKENS"),
        "slotGroups": parse_lua_string_list(source, "SLOT_GROUP_ORDER"),
    }
    problems: list[str] = []
    for key, local in expected.items():
        remote = catalog.get(key)
        if remote == local:
            continue
        remote_list = remote if isinstance(remote, list) else []
        missing = [item for item in remote_list if item not in local]
        extra = [item for item in local if item not in remote_list]
        detail = f"site has {missing or 'nothing'} that Catalog.lua lacks, Catalog.lua has {extra or 'nothing'} the site lacks"
        if not missing and not extra:
            detail = "same members in a different order"
        problems.append(f"{key}: {detail}")
    if problems:
        raise SyncError("catalog differs from the site (" + "; ".join(problems)
                        + "); update Catalog.lua and the fixtures first")


def format_version(version: int) -> str:
    sequence = version % 1000
    date = version // 1000
    year, month, day = date // 10000, date // 100 % 100, date % 100
    days = DAYS_IN_MONTH[month - 1] if 1 <= month <= 12 else 0
    if month == 2 and (year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)):
        days = 29
    if 1 <= sequence and 1000 <= year <= 9999 and 1 <= day <= days:
        return f"{year}.{month:02d}.{day:02d}.{sequence}"
    return str(version)


def lua_string(value: str) -> str:
    escaped = "".join(
        "\\\\" if char == "\\" else '\\"' if char == '"' else f"\\{ord(char):03d}" if ord(char) < 32 else char
        for char in value
    )
    return '"' + escaped + '"'


def render_builtin_lists(lists: list[dict[str, Any]]) -> str:
    lines = [GENERATED_HEADER, "ns.BuiltinLists = {"]
    for item in lists:
        lines.append("  {")
        for key in ("listId", "version", "publishedAt", "title", "author", "importString"):
            value = item[key]
            rendered = str(int(value)) if key in ("version", "publishedAt") else lua_string(value)
            lines.append(f"    {key} = {rendered},")
        # Written only on the default, so other lists' entries don't change when it moves.
        if item.get("isDefault"):
            lines.append("    isDefault = true,")
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_tokens(tokens: list[dict[str, Any]]) -> str:
    lines = [GENERATED_HEADER, "ns.TokenRewards = {}"]
    for token in sorted(tokens, key=lambda entry: entry["tokenItemId"]):
        rewards = ", ".join(str(int(reward)) for reward in sorted(token["rewardItemIds"]))
        lines.append(f"ns.TokenRewards[{int(token['tokenItemId'])}] = {{ {rewards} }}")
    return "\n".join(lines) + "\n"


def unescape_lua_string(escaped: str) -> str:
    raw = bytearray()
    index = 0
    data = escaped.encode("utf-8")
    while index < len(data):
        if data[index] == 0x5C:
            if data[index + 1:index + 2].isdigit():
                raw.append(int(data[index + 1:index + 4]))
                index += 4
            else:
                raw.append(data[index + 1])
                index += 2
        else:
            raw.append(data[index])
            index += 1
    return raw.decode("utf-8")


def read_generated_lists(lua: str) -> dict[str, tuple[str, int]]:
    pattern = re.compile(r'listId = "((?:[^"\\]|\\.)*)",\s*version = (\d+),.*?title = "((?:[^"\\]|\\.)*)",', re.DOTALL)
    return {
        unescape_lua_string(list_id): (unescape_lua_string(title), int(version))
        for list_id, version, title in pattern.findall(lua)
    }


def read_generated_default(lua: str) -> str | None:
    for record in lua.split("\n  {\n")[1:]:
        match = re.match(r'    listId = "((?:[^"\\]|\\.)*)",', record)
        if match and "\n    isDefault = true," in record:
            return unescape_lua_string(match.group(1))
    return None


def read_generated_tokens(lua: str) -> dict[int, list[int]]:
    pattern = re.compile(r"^ns\.TokenRewards\[(\d+)\] = \{ (.*) \}$", re.MULTILINE)
    return {
        int(token_id): sorted(int(reward) for reward in rewards.split(","))
        for token_id, rewards in pattern.findall(lua)
    }


def summarize(old_lua: str, new_lists: list[dict[str, Any]], old_tokens_lua: str,
              new_tokens: list[dict[str, Any]]) -> list[str]:
    old = read_generated_lists(old_lua)
    new = {item["listId"]: (item["title"], item["version"]) for item in new_lists}
    lines: list[str] = []
    for list_id, (title, version) in new.items():
        if list_id not in old:
            lines.append(f'Added: "{title}" ({list_id}) v{format_version(version)}')
    for list_id, (title, _) in old.items():
        if list_id not in new:
            lines.append(f'Removed: "{title}" ({list_id})')
    for list_id, (title, version) in new.items():
        if list_id in old and old[list_id][1] != version:
            lines.append(f'Updated: "{title}" v{format_version(old[list_id][1])} -> v{format_version(version)}')
    new_default = next((item for item in new_lists if item.get("isDefault")), None)
    if read_generated_default(old_lua) != (new_default["listId"] if new_default else None):
        lines.append(f'Default list: "{new_default["title"]}" ({new_default["listId"]})' if new_default
                     else "Default list: none, characters start on the first built-in list")
    old_rewards = read_generated_tokens(old_tokens_lua)
    new_rewards = {int(token["tokenItemId"]): sorted(int(r) for r in token["rewardItemIds"]) for token in new_tokens}
    added = len(new_rewards.keys() - old_rewards.keys())
    removed = len(old_rewards.keys() - new_rewards.keys())
    changed = sum(1 for token_id in new_rewards.keys() & old_rewards.keys()
                  if new_rewards[token_id] != old_rewards[token_id])
    if added or removed or changed:
        lines.append(f"Token mappings: +{added} added, -{removed} removed, {changed} changed")
    return lines or ["No changes."]


def build_outputs(data: dict[str, Any], catalog_path: str) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    try:
        check_catalog(data["catalog"], catalog_path)
        tokens = data["tokens"]
        lists: list[dict[str, Any]] = []
        list_ids = [entry["listId"] for entry in data["lists"]]
        duplicates = sorted({list_id for list_id in list_ids if list_ids.count(list_id) > 1})
        if duplicates:
            raise SyncError(f"duplicate listIds in the response: {', '.join(duplicates)}")
        for entry in data["lists"]:
            try:
                header = decode_import_string(entry["importString"])
            except SyncError as error:
                raise SyncError(f'import string of "{entry["title"]}" ({entry["listId"]}) is invalid: {error}') from error
            if header["listId"] != entry["listId"] or header["version"] != entry["version"]:
                raise SyncError(f'header of "{entry["title"]}" does not match the endpoint '
                                f'(listId {header["listId"]} vs {entry["listId"]}, '
                                f'version {header["version"]} vs {entry["version"]})')
            if header["game"] != "forever":
                raise SyncError(f'"{entry["title"]}" has game "{header["game"]}", expected "forever"')
            # A site from before the default existed sends no flag, which means no default.
            is_default = entry.get("isDefault", False)
            if not isinstance(is_default, bool):
                raise SyncError(f'"{entry["title"]}" has a non-boolean isDefault')
            lists.append({
                "listId": entry["listId"],
                "version": entry["version"],
                "publishedAt": header["publishedAt"],
                "title": entry["title"],
                "author": header["author"],
                "importString": entry["importString"],
                "isDefault": is_default,
            })
    except (KeyError, TypeError) as error:
        raise SyncError(f"unexpected response shape: {error!r}") from error
    defaults = [item["title"] for item in lists if item["isDefault"]]
    if len(defaults) > 1:
        raise SyncError(f"more than one default list in the response: {', '.join(defaults)}")
    return lists, tokens


def read_existing(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def write_temp(path: Path, text: str) -> Path:
    temp = path.with_name(path.name + ".tmp")
    temp.write_bytes(text.encode("utf-8"))
    return temp


def write_atomically(files: dict[Path, str]) -> None:
    """Replaces all files or none, so Lists and Tokens cannot drift out of step."""
    temps: dict[Path, Path] = {}
    try:
        for path, text in files.items():
            temps[path] = write_temp(path, text)
        for path, temp in temps.items():
            os.replace(temp, path)
    finally:
        for temp in temps.values():
            temp.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site", default=DEFAULT_SITE, help="website base URL (default: %(default)s)")
    args = parser.parse_args()
    data_dir = REPO_DIR / "Data"
    try:
        data = fetch_builtin(args.site)
        lists, tokens = build_outputs(data, str(REPO_DIR / "Catalog.lua"))
        new_lists_lua = render_builtin_lists(lists)
        new_tokens_lua = render_tokens(tokens)
        old_lists = read_existing(data_dir / BUILTIN_LISTS_FILE)
        old_tokens = read_existing(data_dir / TOKENS_FILE)
        summary = summarize(old_lists, lists, old_tokens, tokens)
        write_atomically({data_dir / BUILTIN_LISTS_FILE: new_lists_lua, data_dir / TOKENS_FILE: new_tokens_lua})
    except (SyncError, OSError, ValueError, KeyError, TypeError, UnicodeError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    print("\n".join(summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
